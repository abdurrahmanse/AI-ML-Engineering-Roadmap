/**
 * Writes the `sig` for every entry in src/data/topics.ts from the current
 * parsed objectives, and reports coverage.
 *
 * The label sets are read by importing the module (Node strips the types), not
 * by parsing the file as text — a regex over the source silently miscounted
 * when the formatting changed.
 *
 * Run after authoring labels, or after editing a level's .txt and confirming
 * the existing labels still line up:  npm run topics
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { signature } from '../src/lib/sig.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const topicsPath = join(root, 'src/data/topics.ts');

const data = JSON.parse(readFileSync(join(root, 'src/data/levels.json'), 'utf8'));
/** module id -> { level, objective texts } */
const modules = new Map();
for (const level of data.levels) {
  for (const m of level.modules) {
    modules.set(m.id, { level: level.number, texts: m.objectives.map((o) => o.text) });
  }
}

const labelFor = (text) => {
  const clean = text.replace(/^[-•]\s*/, '').replace(/[.;:,]$/, '');
  const words = clean.split(/\s+/);
  return words.length <= 7 ? clean : `${words.slice(0, 7).join(' ')}...`;
};

const byLevel = [...modules.entries()].sort((a, b) => {
  const levelDiff = a[1].level - b[1].level;
  return levelDiff || a[0].localeCompare(b[0], undefined, { numeric: true });
});

const blocks = byLevel.map(([id, mod]) => {
  const labels = mod.texts.map(labelFor);
  return `  '${id}': {\n    sig: '${signature(mod.texts)}',\n    labels: [\n${labels.map((label) => `      ${JSON.stringify(label)},`).join('\n')}\n    ],\n  },`;
});

const source = `/**
 * Short topic labels derived from the current AI/ML Research Roadmap objectives.
 * Regenerated by scripts/sign-topics.mjs whenever source curriculum changes.
 */

export interface TopicSet {
  sig: string;
  labels: string[];
}

export const topics: Record<string, TopicSet> = {
${blocks.join('\n')}
};
`;

writeFileSync(topicsPath, source);
console.log(`signed ${modules.size} module(s) · ${modules.size}/${modules.size} modules have topic labels`);
